"""VeChain through a public Thor node (research 2026-08-27/28).

* The history is in the **node**, not an explorer API: `POST /logs/transfer` (VET)
  and `POST /logs/event` (VTHO, a VIP-180 token: not in the transfer log).
* Criteria are **one-sided**: `sender` and `recipient` are separate fields, a set
  with both demands both. One query per direction, else half the history is missing.
* Amounts are hex. Identity: `txID:clauseIndex` (+ `vtho:` for VTHO).
* The fee is paid in **VTHO**, not VET, and is not in the logs: for a transaction I
  sent, the receipt says who paid (`gasPayer`) and how much (`paid`).
* VTHO generated by holding VET is not a transfer and never appears here; the
  manifest names it under `accrues`, and the app books the difference to the balance as
  income after each fetch (Vanixxx, 2026-10-09).
"""

from __future__ import annotations

from collections.abc import Callable, Iterator
from datetime import datetime

from app.modules.plugins import chain
from app.modules.plugins.contract import Movement

API = "https://mainnet.vechain.org"
NATIVE, FEE_ASSET, DECIMALS = "VET", "VTHO", 18
VTHO_CONTRACT = "0x0000000000000000000000000000456e65726779"
TRANSFER_TOPIC = "0xddf252ad1be2c89b69c2b068fc378daa952ba7f163c4a11628f55a4df523b3ef"
PAGE = 256
RANGE = {"unit": "block", "from": 0, "to": 4_294_967_295}


def _logs(path: str, criteria: dict) -> list[dict]:
    rows: list[dict] = []
    while True:
        body = {
            "range": RANGE,
            "options": {"offset": len(rows), "limit": PAGE},
            "criteriaSet": [criteria],
            "order": "asc",
        }
        batch = chain.http_json(f"{API}/logs/{path}", body)
        if not isinstance(batch, list):
            raise chain.ChainUnavailable("invalid answer")
        rows.extend(batch)
        if len(batch) < PAGE:
            return rows


def _topic(address: str) -> str:
    return "0x" + "0" * 24 + address[2:].lower()


def records(address: str) -> list[dict]:
    """VET transfers and VTHO events, both directions, each once."""
    found: dict[str, dict] = {}
    for side in ("sender", "recipient"):
        for r in _logs("transfer", {side: address}):
            meta = r.get("meta") or {}
            found.setdefault(f"{meta.get('txID')}:{meta.get('clauseIndex')}", r)
    for slot in ("topic1", "topic2"):
        criteria = {"address": VTHO_CONTRACT, "topic0": TRANSFER_TOPIC, slot: _topic(address)}
        for r in _logs("event", criteria):
            meta = r.get("meta") or {}
            found.setdefault(f"vtho:{meta.get('txID')}:{meta.get('clauseIndex')}", r)
    return list(found.values())


def receipt_fee(tx_id: str, address: str):
    r = chain.http_json(f"{API}/transactions/{tx_id}/receipt")
    if not isinstance(r, dict) or (r.get("gasPayer") or "").lower() != address.lower():
        return None
    return chain.units(int(r.get("paid") or "0x0", 16), DECIMALS)


def convert(address: str, rows: list[dict], fee_of: Callable[[str], object] = lambda _tx: None):
    me = address.lower()
    out: list[Movement] = []
    charged: set[str] = set()
    for r in rows:
        meta = r.get("meta") or {}
        if "topics" in r:  # a VTHO event: addresses padded to 32 bytes in topics 1 and 2
            topics = r.get("topics") or []
            sender = "0x" + topics[1][-40:] if len(topics) > 1 else ""
            receiver = "0x" + topics[2][-40:] if len(topics) > 2 else ""
            asset, raw_amount, ident = FEE_ASSET, r.get("data") or "0x0", "vtho:"
        else:
            sender, receiver = r.get("sender") or "", r.get("recipient") or ""
            asset, raw_amount, ident = NATIVE, r.get("amount") or "0x0", ""
        tx = meta.get("txID")
        sent = sender.lower() == me
        fee = None
        if sent and tx not in charged:  # one fee per transaction, at its first clause
            charged.add(tx)
            fee = fee_of(tx)
        out.append(
            chain.transfer(
                sent=sent,
                received=receiver.lower() == me,
                asset=asset,
                amount=chain.units(int(raw_amount, 16), DECIMALS),
                timestamp=chain.seconds(meta["blockTimestamp"]),
                external_id=f"{ident}{tx}:{meta.get('clauseIndex')}",
                sender=sender,
                receiver=receiver,
                fee=fee,
                fee_asset=FEE_ASSET,
                raw=r,
            )
        )
    return out


def fetch(
    address: str,
    since: datetime | None,
    progress: Callable[[dict], None] | None = None,
    key: str | None = None,
) -> Iterator[Movement]:
    rows = records(address)
    if progress:
        progress({"step": "logs", "done": 1, "total": 1, "rows": len(rows)})
    movements = convert(address, rows, lambda tx: receipt_fee(tx, address))
    yield from chain.since_only(movements, since)


def balance(address: str, key: str | None = None, tokens: dict | None = None) -> list:
    body = chain.http_json(f"{API}/accounts/{address}")
    return [
        ("spot", NATIVE, chain.units(int(body.get("balance") or "0x0", 16), DECIMALS)),
        ("spot", FEE_ASSET, chain.units(int(body.get("energy") or "0x0", 16), DECIMALS)),
    ]
